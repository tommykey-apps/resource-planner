/**
 * Lambda Web Function に配置するディレクトリを組み立てる。
 *
 * 出力: `web/dist/web-function/`。CD がこのディレクトリを `aws lambda-web deploy --code` に渡す。
 *
 *   dist/web-function/
 *   ├── index.js        src/lambda/web-function-entry.ts を esbuild でまとめたもの (runtime が最初に読む)
 *   ├── build/          adapter-node の出力 (先に `pnpm build` を済ませておく)
 *   ├── package.json    "type": "module" と本番用の依存
 *   └── node_modules/   本番用の依存だけ。シンボリックリンクなし
 *
 * node_modules を pnpm 既定の配置 (シンボリックリンク + .pnpm) のまま渡すと、CLI がリンクと
 * ドットで始まるディレクトリを zip に入れないため依存が欠ける。node-linker=hoisted で実体を置く。
 * Refs:
 * - https://svelte.dev/docs/kit/adapter-node#Deploying
 * - https://docs.aws.amazon.com/lambda/latest/dg/web-functions-configuration-deployment-package.html
 * - https://pnpm.io/settings#nodelinker
 */
import esbuild from 'esbuild';
import { execFileSync } from 'node:child_process';
import { cp, mkdir, rm, stat } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = resolve(ROOT, 'dist/web-function');

await stat(resolve(ROOT, 'build/index.js')).catch(() => {
	throw new Error('build/index.js がない。先に `pnpm build` を実行する');
});

await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });

await esbuild.build({
	entryPoints: [resolve(ROOT, 'src/lambda/web-function-entry.ts')],
	outfile: resolve(OUT_DIR, 'index.js'),
	bundle: true,
	platform: 'node',
	target: 'node24',
	format: 'esm',
	sourcemap: false,
	banner: { js: '// generated by web/scripts/package-web-function.mjs' }
});

await cp(resolve(ROOT, 'build'), resolve(OUT_DIR, 'build'), { recursive: true });
for (const file of ['package.json', 'pnpm-lock.yaml', 'pnpm-workspace.yaml', '.npmrc']) {
	await cp(resolve(ROOT, file), resolve(OUT_DIR, file));
}

// 本番用の依存だけを実体ファイルで入れる。install script は不要 (ネイティブモジュールを実行時に使わない)
execFileSync(
	'pnpm',
	['install', '--prod', '--frozen-lockfile', '--ignore-scripts', '--config.node-linker=hoisted'],
	{ cwd: OUT_DIR, stdio: 'inherit' }
);

// 認証設定と lockfile は実行時に不要。.npmrc は CLI も除外するが、配布物に残さない
for (const file of ['pnpm-lock.yaml', 'pnpm-workspace.yaml', '.npmrc']) {
	await rm(resolve(OUT_DIR, file));
}

console.log(`Packaged: ${OUT_DIR}`);
