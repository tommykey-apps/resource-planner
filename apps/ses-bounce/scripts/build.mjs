/**
 * SES bounce handler Lambda の bundle script (#134)。
 *
 * 出力: `apps/ses-bounce/dist/index.mjs`
 * Terraform の `data.archive_file.ses_bounce_handler` がこのディレクトリを zip 化する。
 *
 * web アプリと共有するキーと項目の形は workspace のパッケージ `@resource-planner/db` から
 * 読む。TS のまま公開しているので、esbuild がそのまま bundle する。
 */
import esbuild from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { rm, mkdir } from 'node:fs/promises';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = resolve(ROOT, 'dist');

await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });

await esbuild.build({
	entryPoints: [resolve(ROOT, 'src/handler.ts')],
	outfile: resolve(OUT_DIR, 'index.mjs'),
	bundle: true,
	platform: 'node',
	target: 'node22',
	format: 'esm',
	minify: false,
	sourcemap: 'inline',
	// AWS SDK v3 は runtime にも入っているが、版を lockfile で固定するため external にせず bundle に含める
	// Ref: https://docs.aws.amazon.com/lambda/latest/dg/lambda-nodejs.html#nodejs-sdk-included
	banner: {
		js: '// generated by apps/ses-bounce/scripts/build.mjs (#134)'
	}
});

console.log(`Bundled: ${OUT_DIR}/index.mjs`);
