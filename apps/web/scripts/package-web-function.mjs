/**
 * Lambda Web Function に配置するディレクトリを組み立てる。
 *
 * 出力: `apps/web/dist/web-function/`。CD がこのディレクトリを `aws lambda-web deploy --code` に渡す。
 *
 *   dist/web-function/
 *   ├── index.js        src/lambda/web-function-entry.ts を esbuild でまとめたもの (runtime が最初に読む)
 *   ├── build/          adapter-node の出力 (先に `pnpm build` を済ませておく)
 *   ├── package.json    "type": "module" と本番用の依存
 *   └── node_modules/   本番用の依存だけ。シンボリックリンクなし
 *
 * node_modules を pnpm 既定の配置 (シンボリックリンク + .pnpm) のまま渡すと、CLI がリンクと
 * ドットで始まるディレクトリを zip に入れないため依存が欠ける。node-linker=hoisted で実体を置く。
 *
 * lockfile は workspace のルートにあるので、`pnpm deploy` で web だけの本番用の依存を取り出す。
 * - `--legacy` は使わない。legacy と hoisted の組み合わせでは lockfile を使わずに版を解決し直す
 * - deploy の前提条件 injectWorkspacePackages はルートの pnpm-workspace.yaml に書いてある
 * - 複製するファイルは package.json の `files` (build/ だけ) で絞る
 * Refs:
 * - https://svelte.dev/docs/kit/adapter-node#Deploying
 * - https://docs.aws.amazon.com/lambda/latest/dg/web-functions-configuration-deployment-package.html
 * - https://pnpm.io/settings#nodelinker
 * - https://pnpm.io/cli/deploy
 */
import esbuild from 'esbuild';
import { execFileSync } from 'node:child_process';
import { rm, stat } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = resolve(ROOT, 'dist/web-function');

await stat(resolve(ROOT, 'build/index.js')).catch(() => {
	throw new Error('build/index.js がない。先に `pnpm build` を実行する');
});

await rm(OUT_DIR, { recursive: true, force: true });

// 本番用の依存だけを実体ファイルで入れる。install script は不要 (ネイティブモジュールを実行時に使わない)。
// deploy は空でない出力先を拒むので、index.js はこの後に置く
execFileSync(
	'pnpm',
	[
		'--filter',
		'@resource-planner/web',
		'deploy',
		'--prod',
		'--ignore-scripts',
		'--config.node-linker=hoisted',
		OUT_DIR
	],
	{ cwd: ROOT, stdio: 'inherit' }
);

// deploy が出力先に書く lockfile は実行時に不要
await rm(resolve(OUT_DIR, 'pnpm-lock.yaml'), { force: true });

await esbuild.build({
	entryPoints: [resolve(ROOT, 'src/lambda/web-function-entry.ts')],
	outfile: resolve(OUT_DIR, 'index.js'),
	bundle: true,
	platform: 'node',
	target: 'node24',
	format: 'esm',
	sourcemap: false,
	banner: { js: '// generated by apps/web/scripts/package-web-function.mjs' }
});

console.log(`Packaged: ${OUT_DIR}`);
